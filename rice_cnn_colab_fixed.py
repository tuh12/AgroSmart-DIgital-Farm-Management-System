# ---------- Datasets ----------
if 'train_ds' not in globals() or 'val_ds' not in globals():
    print("Creating datasets...")
    train_df, val_df = train_test_split(
        df, test_size=0.15, random_state=SEED, stratify=df["label_id"]
    )

    def load_image(path, label):
        image_bytes = tf.io.read_file(path)
        image = tf.io.decode_image(image_bytes, channels=3, expand_animations=False)
        image.set_shape([None, None, 3])
        image = tf.image.resize(image, [IMG, IMG])
        image = tf.keras.applications.mobilenet_v2.preprocess_input(image)
        return image, tf.one_hot(label, NUM_CLASSES)

    aug = tf.keras.Sequential([
        tf.keras.layers.RandomFlip("horizontal_and_vertical"),
        tf.keras.layers.RandomRotation(0.12),
        tf.keras.layers.RandomZoom(0.12),
    ])

    def make_dataset(frame, training=False):
        ds = tf.data.Dataset.from_tensor_slices((
            frame["filepath"].astype(str).values,
            frame["label_id"].values.astype(np.int32)
        ))
        if training:
            ds = ds.shuffle(len(frame), seed=SEED, reshuffle_each_iteration=True)
        ds = ds.map(load_image, num_parallel_calls=AUTOTUNE)
        if training:
            ds = ds.map(lambda x, y: (aug(x, training=True), y),
                        num_parallel_calls=AUTOTUNE)
        else:
            ds = ds.cache()
        return ds.batch(BATCH).prefetch(AUTOTUNE)

    train_ds = make_dataset(train_df, training=True)
    val_ds = make_dataset(val_df, training=False)

    weights = compute_class_weight(
        class_weight="balanced",
        classes=np.arange(NUM_CLASSES),
        y=train_df["label_id"].values
    )
    class_weight = {int(i): float(w) for i, w in enumerate(weights)}
