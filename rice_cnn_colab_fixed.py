def diagnose(image_path, top_k=3):
    img = tf.keras.utils.load_img(image_path, target_size=(IMG, IMG))
    arr = tf.keras.utils.img_to_array(img)
    arr = tf.keras.applications.mobilenet_v2.preprocess_input(arr)
    probs = model.predict(np.expand_dims(arr, axis=0), verbose=0)[0]

    order = np.argsort(probs)[::-1][:min(top_k, NUM_CLASSES)]
    label = class_names[order[0]]
    conf = probs[order[0]] * 100

    display(Image(filename=image_path, width=320))
    print("=" * 55)
    print("Top predictions:")
    for i in order:
        print(f"  - {class_names[i]:<28} {probs[i] * 100:6.2f}%")
    print("=" * 55)

    if conf < MIN_CONFIDENCE or label not in PADDY_INFO:
        print("Result unclear (low confidence). Retake photo: closer, daylight, focus on affected leaf.")
        return

    info = PADDY_INFO[label]
    print(f"\nDiagnosis : {info['issue']}")
    print(f"Confidence: {conf:.1f}%")
    print(f"Severity  : {info['severity']}")
    print("\nTreatment:")
    for n, step in enumerate(info["treatment"], 1):
        print(f"  {n}. {step}")
    print(f"\nPrevention (Solution):\n  {info['prevention']}")
    if info["pesticide"]:
        print(f"\nPesticide note:\n  {info['pesticide']}")
    print(f"\n{DISCLAIMER}")


uploaded_test = files.upload()
for fname in uploaded_test:
    print(f"\n######## {fname} ########")
    diagnose(fname)

